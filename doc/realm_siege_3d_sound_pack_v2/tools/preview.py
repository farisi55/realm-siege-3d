#!/usr/bin/env python3
"""
Realm Siege 3D — Sound Pack V2 · preview page generator.

Reads `manifest.json` (regenerate it first with `tools/manifest.py`), measures the documented
unused files, and writes `preview.html` — a self-contained audition page for all 80 shipped
files: grouped by folder/hero, searchable, with voice name, gain, role, duration, channel mode
and decoded levels per card, and the unused set clearly marked at the end.

Re-run after any re-encode:

    python doc/realm_siege_3d_sound_pack_v2/tools/preview.py
"""
from __future__ import annotations

import html
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
PACK_DOC = HERE.parent
ROOT = HERE.parents[2]
PACK_DIR = ROOT / 'public' / 'audio' / 'realm-siege'
MANIFEST = PACK_DOC / 'manifest.json'
OUT = PACK_DOC / 'preview.html'
SR = 44100

sys.path.insert(0, str(HERE))
import measure as M  # noqa: E402


def probe(rel: str) -> dict:
    path = PACK_DIR / rel
    ch = int(subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'a:0',
                             '-show_entries', 'stream=channels', '-of', 'csv=p=0', str(path)],
                            capture_output=True, text=True, check=True).stdout.strip())
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.float32).astype(np.float64).reshape(-1, ch)
    x = x.T if ch > 1 else x[:, 0]
    return {
        'channels': ch, 'durationS': round(len(M.to_mono(x)) / SR, 2),
        'peakDb': round(M.peak_db(x), 1), 'rmsDb': round(M.rms_db(x), 1),
        'crestDb': round(M.crest_db(x), 1),
    }


def esc(s: str) -> str:
    return html.escape(str(s), quote=True)


def main() -> int:
    if not MANIFEST.exists():
        print('manifest.json missing — run tools/manifest.py first', file=sys.stderr)
        return 1
    man = json.loads(MANIFEST.read_text(encoding='utf-8'))

    sounds = []
    for f in man['files']:
        sounds.append({**f, 'used': True})
    for u in man['unused']:
        try:
            info = probe(u['path'])
        except Exception as e:  # noqa: BLE001
            print(f'warning: could not measure {u["path"]}: {e}', file=sys.stderr)
            info = {'channels': 1, 'durationS': 0, 'peakDb': None, 'rmsDb': None, 'crestDb': None}
        sounds.append({'voice': None, 'path': u['path'], 'gain': None, 'role': 'unused',
                       'v2': False, 'used': False, 'reason': u['reason'], **info})

    counts = man['counts']
    data = json.dumps(sounds, ensure_ascii=False)
    root = esc('../../public/audio/realm-siege/')
    html_doc = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Realm Siege 3D — Sound Pack v2 preview</title>
<style>
:root{{color-scheme:dark;--bg:#101522;--panel:#1a2232;--line:#34415b;--gold:#f6c953;--text:#e7edf8;--muted:#a3afc5;--good:#7fd6a4;--dim:#7d8aa5}}
*{{box-sizing:border-box}}body{{margin:0;background:var(--bg);color:var(--text);font:15px/1.5 system-ui,Segoe UI,sans-serif;padding:24px;max-width:1240px;margin-inline:auto}}
h1{{font-size:clamp(24px,4vw,36px);margin:0 0 6px;color:var(--gold)}}p{{color:var(--muted);margin:0 0 14px}}
.toolbar{{position:sticky;top:0;background:#101522ed;backdrop-filter:blur(12px);padding:12px 0;display:flex;gap:10px;flex-wrap:wrap;z-index:2}}
input,select,button{{border:1px solid var(--line);border-radius:9px;padding:10px 12px;background:var(--panel);color:var(--text)}}input{{min-width:240px;flex:1}}button{{cursor:pointer}}button:hover{{border-color:var(--gold)}}
section{{margin:22px 0}}h2{{font-size:17px;color:var(--gold);margin-bottom:10px}}.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(min(100%,330px),1fr));gap:10px}}
.item{{background:var(--panel);border:1px solid var(--line);border-radius:12px;padding:12px;display:grid;grid-template-columns:1fr auto;gap:8px;align-items:center}}
.name{{font-weight:650;overflow-wrap:anywhere}}.meta{{font-size:12px;color:var(--muted)}}audio{{grid-column:1/-1;width:100%;height:34px}}
.pill{{font-size:11px;color:#132034;background:var(--gold);padding:3px 7px;border-radius:99px;font-weight:700}}.pill.v2{{background:var(--good)}}.pill.keep{{background:var(--dim)}}.pill.unused{{background:#e8a0a0}}
.topline{{display:flex;justify-content:space-between;gap:10px;align-items:center}}
</style></head>
<body>
<h1>Realm Siege 3D — Sound Pack v2</h1>
<p>Audition page for all {counts['totalOnDisk']} shipped files ({counts['mapped']} mapped = {counts['v2Authored']} V2-authored + {counts['v1Kept']} kept V1 · {counts['unused']} documented unused). Play one file at a time to compare. Generated by <code>tools/preview.py</code> from <code>manifest.json</code> — do not hand-edit.</p>
<div class="toolbar">
<input id="search" placeholder="Search file / voice / role…">
<select id="category">
<option value="all">All categories</option>
<option value="ui">UI</option><option value="combat">Combat</option><option value="heroes">Hero abilities</option>
<option value="structures">Structures</option><option value="ambience">Ambience</option><option value="unused">Unused (documented)</option>
</select>
<select id="origin"><option value="all">V2 + V1</option><option value="v2">V2-authored only</option><option value="v1">Kept V1 only</option><option value="unused">Unused only</option></select>
<button id="stop">Stop all</button>
</div>
<div id="content"></div>
<script>
const root={json.dumps(root)};
const sounds={data};
const groups={{
'UI':'ui','Combat':'combat','Hero Abilities':'heroes','Structures':'structures','Ambience':'ambience','Unused (documented)':'unused'
}};
const content=document.getElementById('content');
function catOf(s){{if(!s.used)return 'unused';return s.path.split('/')[0];}}
function fmt(s){{
  const ch=s.channels===2?'stereo'+(s.role==='bed'?'':' / two-channel'):'mono';
  const bits=[];
  bits.push(s.used?('gain '+s.gain):'unused');
  bits.push(s.role);
  bits.push(s.durationS+'s');
  bits.push(ch);
  if(s.peakDb!==null&&s.peakDb!==undefined)bits.push('peak '+s.peakDb+' dB');
  if(s.rmsDb!==null&&s.rmsDb!==undefined)bits.push('rms '+s.rmsDb+' dB');
  return bits.join(' · ');
}}
function render(){{
  const q=document.getElementById('search').value.toLowerCase();
  const cat=document.getElementById('category').value;
  const org=document.getElementById('origin').value;
  content.innerHTML='';
  for(const [heading,prefix] of Object.entries(groups)){{
    const filtered=sounds.filter(s=>{{
      if(prefix==='unused'){{if(s.used)return false;}}
      else if(!s.used&&heading!=='Unused (documented)'){{if(catOf(s)!==prefix)return false;}}
      if(prefix!=='unused'&&s.used&&catOf(s)!==prefix)return false;
      if (org==='v2'&&!s.v2)return false;
      if (org==='v1'&&(s.v2||!s.used))return false;
      if (org==='unused'&&s.used)return false;
      if(cat!=='all'&&cat!==prefix)return false;
      const hay=((s.voice||'')+' '+s.path+' '+s.role+(s.reason?' '+s.reason:'')).toLowerCase();
      return hay.includes(q);
    }});
    if(!filtered.length)continue;
    const sec=document.createElement('section');
    const h2=document.createElement('h2');
    h2.textContent=heading+' ('+filtered.length+')';
    sec.appendChild(h2);
    const grid=document.createElement('div');grid.className='grid';
    for(const s of filtered){{
      const card=document.createElement('div');card.className='item';
      const left=document.createElement('div');
      const name=document.createElement('div');name.className='name';
      name.textContent=(s.voice?s.voice+' — ':'')+s.path;
      const meta=document.createElement('div');meta.className='meta';
      meta.textContent=fmt(s)+(s.reason?' · '+s.reason:'');
      left.append(name,meta);
      const badge=document.createElement('span');
      badge.className='pill '+(s.used?(s.v2?'v2':'keep'):'unused');
      badge.textContent=s.used?(s.v2?'V2':'V1'):'UNUSED';
      const player=document.createElement('audio');
      player.controls=true;player.preload='none';player.src=root+s.path;
      card.append(left,badge,player);
      grid.appendChild(card);
    }}
    sec.appendChild(grid);content.appendChild(sec);
  }}
}}
document.getElementById('search').addEventListener('input',render);
document.getElementById('category').addEventListener('change',render);
document.getElementById('origin').addEventListener('change',render);
document.getElementById('stop').addEventListener('click',()=>document.querySelectorAll('audio').forEach(a=>{{a.pause();a.currentTime=0}}));
render();
</script></body></html>
"""
    OUT.write_text(html_doc, encoding='utf-8')
    print(f'preview.html written: {len(sounds)} files ({sum(1 for s in sounds if not s["used"])} unused)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
